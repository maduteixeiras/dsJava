public class ForEach {
    public static void main(String[] args) {

        // O laço for-each foi introduzido no Java 5. Ele elimina a necessidade de controlar índices ou contadores manuais como i < tamanho
    String[] nomes = {"Anna", "Anna"};
    for (String tam : nomes) {
        System.out.println(tam);
    }
    }
    
}
